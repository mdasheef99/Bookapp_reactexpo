const { RuleTester } = require('eslint');
const rule = require('../no-raw-style-values');

const tester = new RuleTester({
    languageOptions: {
        parser: require('@typescript-eslint/parser'),
        parserOptions: { ecmaFeatures: { jsx: true } },
    },
});

const invalid = (code, messageId, data, count = 1) => ({
    code,
    filename: 'example.tsx',
    errors: Array.from({ length: count }, () => ({ messageId, ...(data && { data }) })),
});

tester.run('no-raw-style-values', rule, {
    valid: [
        'const s = { padding: 0 };',
        'const s = { margin: 1 };',
        'const s = { marginTop: -1, padding: -0, gap: +1 };',
        "const s = { padding: '50%', margin: 'auto' };",
        'const s = { gap: StyleSheet.hairlineWidth };',
        'const s = { padding: LIBRARY_SPACING.md };',
        'const s = { padding: LIBRARY_SPACING.md * 2 };',
        'const s = { padding: 12 / 2, margin: 12 % 5, gap: 2 ** 3 };',
        'const s = { fontSize: LIBRARY_TEXT.body.fontSize };',
        'const s = { borderWidth: 2, borderRadius: 12, width: 44, height: 44, opacity: 0.5, letterSpacing: 2, shadowRadius: 4 };',
        'const s = { color: colors.accent };',
        "'transparent'; 'red'; '#'; '#12'; '#12345'; '#ggg';",
        "import value from '#abc';",
        "export { value } from '#abc';",
        "export * from '#abc';",
        "const s = { '#fff': true };",
        'const { padding } = styles;',
        "type C = '#fff';",
        'type C = `#fff`;',
        'const s = { [padding]: 12 };',
        'const s = { padding: Math.max(insets.top, 8), margin: [12], gap: { value: 8 }, fontSize: () => 14 };',
        'const s = { padding: count > 8 ? 0 : 1 };',
        'const s = { padding: -offset };',
        'const s = `#${value}`;',
        '<Text>#abc</Text>;',
    ].map(code => ({ code, filename: 'example.tsx' })),
    invalid: [
        invalid("const s = { color: '#fff' };", 'rawColor', { value: '#fff' }),
        invalid("'#FFFFFF';", 'rawColor', { value: '#FFFFFF' }),
        invalid("'#ffff';", 'rawColor', { value: '#ffff' }),
        invalid("'#11223344';", 'rawColor', { value: '#11223344' }),
        invalid('`#abc`;', 'rawColor', { value: '#abc' }),
        invalid("'rgba(0,0,0,0.5)';", 'rawColor'),
        invalid("'gradient rgb(0, 0, 0) stop';", 'rawColor'),
        invalid("' hsl(120, 50%, 50%) ';", 'rawColor'),
        invalid('`hsla(120, 50%, 50%, 0.5)`;', 'rawColor'),
        invalid("'  #abc  ';", 'rawColor', { value: '#abc' }),
        invalid('<View color="#abc" />;', 'rawColor'),
        invalid('const s = { fontSize: 14 };', 'rawFont', { key: 'fontSize' }),
        invalid('const s = { lineHeight: 20 };', 'rawFont', { key: 'lineHeight' }),
        invalid('const s = { fontSize: 0, lineHeight: -1 };', 'rawFont', undefined, 2),
        invalid('const s = { padding: 12 };', 'rawSpacing', { key: 'padding' }),
        invalid('const s = { marginTop: -4 };', 'rawSpacing', { key: 'marginTop' }),
        invalid('const s = { gap: 8 };', 'rawSpacing', { key: 'gap' }),
        invalid('const s = { paddingTop: insets.top + 8 };', 'rawSpacing', { key: 'paddingTop' }),
        invalid('const s = { paddingHorizontal: compact ? 12 : 16 };', 'rawSpacing', { key: 'paddingHorizontal' }, 2),
        invalid('const s = { gap: a || 6 };', 'rawSpacing', { key: 'gap' }),
        invalid('const s = { fontSize: 14 as number };', 'rawFont', { key: 'fontSize' }),
        invalid('const s = { padding: (12 satisfies number)! };', 'rawSpacing', { key: 'padding' }),
        invalid('const s = { margin: +4 };', 'rawSpacing', { key: 'margin' }),
        invalid('const s = { padding: 4 - 6 };', 'rawSpacing', { key: 'padding' }, 2),
        invalid('const s = { gap: 6 && 8 };', 'rawSpacing', { key: 'gap' }, 2),
        invalid('const s = { gap: a ?? 6 };', 'rawSpacing', { key: 'gap' }),
        invalid("const s = { 'paddingEnd': 8 };", 'rawSpacing', { key: 'paddingEnd' }),
        invalid("const s = { ['#fff']: true };", 'rawColor'),
        invalid("const s = { color: '#fff' as const };", 'rawColor', { value: '#fff' }),
        invalid("const s = { color: 'rgba(0,0,0,0.5)' satisfies string };", 'rawColor'),
        invalid('const s = { color: `#abc` as string };', 'rawColor', { value: '#abc' }),
        ...[
            'padding', 'paddingTop', 'paddingBottom', 'paddingLeft', 'paddingRight',
            'paddingHorizontal', 'paddingVertical', 'paddingStart', 'paddingEnd',
            'margin', 'marginTop', 'marginBottom', 'marginLeft', 'marginRight',
            'marginHorizontal', 'marginVertical', 'marginStart', 'marginEnd',
            'gap', 'rowGap', 'columnGap',
        ].map(key => invalid(`const s = { ${key}: 9 };`, 'rawSpacing', { key })),
    ],
});
